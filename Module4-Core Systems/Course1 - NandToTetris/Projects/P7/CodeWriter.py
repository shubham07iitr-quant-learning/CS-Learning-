    ##Below are the functions we wished for above, all of them are supposed to return a list of instructions 

    """
    Signature:self, segment: Str, index: Str > Assembly Code List: List
    Purpose:
        When operating with segment where segment in: ["local", "argument", "this", "that"]:
            - First we will find the mapping of segment from memorymapping
            - Get the actual addresss at that mrmoey mapping  to D register (@memorymapping, D=M)
            - Then we get index to A register (@index)
            - Then we do D=D+A 
            - Then we set A=D
        When we are operating for addr=temp+index, where segment = "temp" and index=index:
            - We will first get 5 to D register (@5, D=A)
            - Then we get index to A register (@index)
            - Then we do D=D+A
            - Then we set A=D
        When we are operating for addr=*SP, where segment = "PointerSP", index=0, here is what we will do:
            - First we get SP to A register , A=SP
            - Then we simply do A=M , which will get the address to 
    """
    def setARegister(self, segment, index):
        templist = []
        if segment in ["local", "argument", "this", "that"]:
            segmentmap = self.memorymapping[segment]
            templist.append("@"+segmentmap)
            templist.append("D=M")
            templist.append("@"+index)
            templist.append("D=D+A")
            templist.append("A=D")
        elif segment == "temp":
            templist.append("@5")
            templist.append("D=A")
            templist.append("@"+index)
            templist.append("D=D+A")
            templist.append("A=D")
        elif segment == "PointerSP":
            templist.append("@SP")
            templist.append("A=M")
        else:
            raise ValueError("This method is not applicable for the given segment value")
        return templist

    """
    Signature: self>Assembly Code List: List
    Purpose:
        *sp=*addr
        We assume that A register is already updated with the right address
        The objective is to realise the following pseudo assmebly *sp=*addr, and it can be done using hte below instructions:
            - We need to understand that in setAregister method, we already have the right address in our A register already, 
            - so we just need (D=M), which will get value at addr in D
            - Let's get the value at *addr which needs to go to *SP (A=D, D=M), now D has the value which needs to be updated 
            - Now let's get to A the address which needs to be updated, or *SP (@SP, A=M), now A has the address which needs to be updated
            - And finally we have (M=D) and we will get our desired output

        Finally we return the list of instructions as templist
    """
    def setPointerSPToPointerAddress(self):
        templist=[]
        templist.append("D=M")
        templist.extend(["@SP", "A=M"])
        templist.append("M=D")
        return templist

    """
    Signature: self> Assembly Code List: List
    Purpose:
        To increment SP value stored at SP memory or RAM[0], which can be done in the following ways:
            - First we get SP to A register (@SP)
            - Then we store SP+1 in D (D=M+1)
            - And finally we get this value in RAM[0] (M=D)
        Finally we return the list of instructions as templist
    """
    def incrementSP(self):
        templist=[]
        templist.append("@SP")
        templist.append("M=M+1")
        return templist

    """
    Signature:  self, value:Str > Assembly Code List: List
    Purpose:
        *SP = i , where i could be some value i such as 1,2,3, or could be a pre-defined variable THIS or THAT
        For both the cases, list of instructions is same as follows:
            - Since we can't directly do M=value, we need to first get teh corresponidng value in D using (@value, D=A)
            - And then We simply get the address to be updated as folows (@SP, A=M)
            - And then update this to the value from the D register (M=D)
        Finally we return the list of instructions as templist
    """
    def setPointerSPToValue(self, value):
        templist = []
        if value not in ["THIS", "THAT"]:
            templist.extend(["@" + value, "D=A"])
        else:
            templist.extend(["@" + value, "D=M"])
        templist.extend(["@SP", "A=M"])
        templist.append("M=D")
        return templist

    
    """
    
    Signature: self> Assembly Code List: List
    Purpose:
        To decrement SP value stored at SP memory or RAM[0], which can be done in the following ways:
            - First we get SP to A register (@SP)
            - Then we store SP+1 in D (D=M-1)
            - And finally we get this value in RAM[0] (M=D)
        Finally we return the list of instructions as templist
    """
    def decrementSP(self):
        templist=[]
        templist.append("@SP")
        templist.append("M=M-1")
        return templist

    """
    Signature: self, value:Str > Assembly Code List: List
    Purpose:
        
        Assuming that A register is already filled up with relevant address, his function solves for the following  cases:
            - *addr=*SP , this is applicable when value == "PointerSP", and will have the following instrucitons:
                - Let's store the address value in D first and then somewhere safe (D=A, @13, M=D) ##Now 13 has the address which is to be updted
                - Then let's get the value which needs to be updated (@SP, A=M, D=M) // Now D has the value which needs to be udpated
                - Now let's again load the address which needs to be updated (@13, A=M)
                - And now, finally we update the address (M=D) and our #addr will be updated with *SP
            - *addr=D, this shouldnt be too difficult:
                - We do (A=M) ## Now A has the address which is to be updated
                - And we imply copy the value of D to M (M=D)
            - *addr=0/1, should be straightforward:
                - We first get the address to be updated (A=M)
                - And then simply update it to the value passed (M=value)

        Finally we return the list of instructions as templist

    """
    def setAddressPointerToValue(self, value):
        templist = []
        if value == "PointerSP":
            templist.extend(["D=A", "@13", "M=D"])
            templist.extend(["@SP", "A=M", "D=M"])
            templist.extend(["@13", "A=M"])
            templist.append("M=D")
        elif value == "D":
            templist.append("A=M")
            templist.append("M=D")
        elif value in ["0", "-1"]:
            templist.append("A=M")
            templist.append("M="+value)
        else:
            raise ValueError("Please pass the right value for this method")
        return templist


    """
    Signature : self, index:Str > Assembly Code List: List
    Purpose:
        If index == "0" > THIS=*SP
        If index == "1" > THAT=*SP
        Here is the instruction, for THIS:
            - Get value to be updated in D (@SP, A=M D=M)
            - Now get THIS on A and update it (@THIS, M=D)
        We follow the same for THAT
        Finally we return the list of instructions as templist

    """
    def setThisThatToPointerSP(self, index):
        templist = []
        templist.extend(["@SP", "A=M","D=M"])
        if index == "0":
            templist.extend(["@THIS", "M=D"])
        elif index == "1":
            templist.extend(["@THAT", "M=D"])
        else:
            raise ValueError("Please pass the right index for this method")
        return templist
        

    """
    Signature: self, value1: None or Str, operation: None or Str, value2: Str > Assembly Code List:List
    Purpose:
        Will solve for the following possibilities:
            - D= *addr, when value1=None, operation=None, value2=*addr
                - This is simply solved by doing (D=M)
            - D= -D or D=!D, when value1=None, operation = neg or not, value2=D
                - This is simply achieved by doing (D=[operation]D)
            - D= D (opearation) *addr, this will also be straightforward
                - D = D [operation] M
        Finally we return the list of instructions as templist
    """
    def setDRegisterToComputation(self, value1, operation, value2):
        templist= []
        if value1==None and operation == None:
            templist.append("D=M")
        elif value1 == None:
            templist.append("D="+self.arithemeticmap[operation]+"D")
        else:
            templist.append("D=D"+self.arithemeticmap[operation]+"M")
        return templist


