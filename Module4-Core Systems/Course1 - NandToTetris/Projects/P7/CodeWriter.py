##This is the module which takes inputs from the Parser module, and actually coverts a single VM instruction into relevant assmbly code for Hack machine


"""
    Type/Interpretation:
        This module will be responsible for generating the corresponding Hack assembly code for 2 categories of instructions
            - Arithemetic (9 commands): add, sub, neg, eq, gt, lt, and, or , not
            - Memory Access (2 commands): 
                - push <segment> <xxx>
                - pop <segment> <xxx>
                - Segment could be of 8 types: ARG, LCL, THIS, THAT, TEMP, POINTER, STATIC, CONSTANT

        For branching, and function instructions we will wait till module 8 to get that done
        In terms of organisation , this module will offer the following functions:
            - __init__ method which will initialise the object with a filename field, and a list codelist, which will have the assembly instructions we are converting for the given object
            - writeArithemetic method which will operate on C_ARITHEMETIC command type and generate the corresponding Hack assembly code
            - writePushPop method which will operate on pushpop commands and generate the necessary Hack assembly code
            - Private methods to be used by interface methods 
        We will write pseduo assembly for each of the methods, and write helper functions for each of the pseudo assembly code
        Codes generated by writeArithemetic and writePushPop will be appended to the codelist field

"""


class CodeWriter():
    """
    TEMPLATE:
        FIELDS:
            ...self.filename                                                            ...Str
            ...self.codelist                                                            ...List 
            ...self.memorymapping                                                       ...Dictionary
            ...self.arithemeticmap                                                      ...Dictionary
            ...self.label_counter                                                       ...int
        METHODS:
            ...self.__init__(self)                                                 ...No return (only initialises the obejct)
            ...self.writeArithemetic (self, code:Str)                              ...No return (only updates code in codelist for Arithemetic commands)
            ...self.writePushPop (self, code:Str, segment: Str, index: Int)        ...No return (only updates code in codelist for Push Pop commands)
    """
    
    def __init__(self, filename):
        self.filename = filename 
        self.codelist = [] ##this is the list which will be updated as and when a new instruction is decoded
        self.memorymapping = {"argument": "ARG", "local": "LCL", "this": "THIS", "that": "THAT", "temp": "TEMP"}
        self.arithemeticmap = {"add": "+", "sub": "-", "eq":"-", "gt": "-", "lt": "-", "neg": "-", "not": "!", "and": "&", "or": "|"}
        self.label_counter = 0 ##To be utilised for eq, gt, lt subroutines in writeArithemetic routine

    """
    Signature: self, code:Str, segment: Str, index: Int > No return (Updates codelist with the corresponding code)
    Purpose:
        This method is supposed to work on a instruction of type "push/pop segment index" and return the corresponding Hack assembly code as per the following pseudo specifications
            pop segment i: addr = segment + i; SP-- ; *addr = *SP      //DONE
            push segment i: addr=segment + i; *SP = *addr; SP++        //DONE
            push constant i: *SP = i; SP++                             //DONE
            push temp i: addr=5+i; *SP = *addr ; SP++                  //DONE
            pop temp i: addr=5+i; SP--; *addr = *SP                    //DONE
            push static i: addr=filename.i; *SP=*addr;SP++             //DONE
            pop static i: addr=filename.i; SP--; *addr = *SP           //DONE
            push pointer 0/1: *SP = THIS/THAT, SP++                    //DONE
            pop pointer 0/1: SP--; THIS/THAT = *SP                     
        We will also add a comment based code - for e.g. for push constant 100, 1st instruction will always be - "//push constant 100"
        FInal output will be codelist will be updated as "push constant 0": [xx,yy,zz...] 
    """
    def writePushPop(self, code, segment, index):
        templist = [] ##Templist in which we will store the relevant instructions
        templist.append("//"+" "+code+" " +segment + " " + index) ##First instruction becomes comment 
        if code=="push":
            if segment in ["local", "argument", "this", "that", "temp"]:
                templist.extend(self.setARegister(segment, index)) ##Will need to define this later ; this is equivalent to saing addr =segment+1, we will also need to define for temp here
                templist.extend(self.setPointerSPToPointerAddress()) ##Equivalent to *SP = *addr
                templist.extend(self.incrementSP()) ## SP++
            elif segment in ["constant"]:
                templist.extend(self.setPointerSPToValue(index)) ##*SP=i
                templist.extend(self.incrementSP()) ## SP++
            elif segment in ["static"]:
                templist.append("@"+self.filename[:-3]+"."+index) ## this represents that static variable is being defined as @filename.index
                templist.extend(self.setPointerSPToPointerAddress()) ##Equivalent to *SP = *addr
                templist.extend(self.incrementSP()) ## SP++
            elif segment in ["pointer"]:
                if index == "0":
                    templist.extend(self.setPointerSPToValue("THIS")) ##*SP = THIS , Need to configure this in our private method of setpointerSP to value
                if index == "1":
                    templist.extend(self.setPointerSPToValue("THAT")) ## *SP = THAT, Need to configure this in our private method of setpointerSP to value
                templist.extend(self.incrementSP())
        elif code=="pop":
            if segment in ["local", "argument", "this", "that", "temp"]:
                templist.extend(self.setARegister(segment, index))  ## compute addr into A
                templist.extend(["D=A", "@13", "M=D"])              ## save addr to R13
                templist.extend(self.decrementSP())                  ## SP--
                templist.extend(["@SP", "A=M", "D=M"])              ## D = *SP
                templist.extend(["@13", "A=M"])                      ## reload addr
                templist.append("M=D")                               ## *addr = D
            elif segment in ["static"]:
                templist.append("@"+self.filename[:-3]+"."+index)
                templist.extend(["D=A", "@13", "M=D"])              ## save addr to R13, need to save the address or it will get overridden
                templist.extend(self.decrementSP())                  ## SP--
                templist.extend(["@SP", "A=M", "D=M"])              ## D = *SP
                templist.extend(["@13", "A=M"])                      ## reload addr
                templist.append("M=D")                               ## *addr = D

            elif segment in ["pointer"]:
                templist.extend(self.decrementSP()) ##SP--; need to be defined
                templist.extend(self.setThisThatToPointerSP(index)) ##THIS/THAT=*SP , needs to be defined
        
        else:
            raise ValueError("The given command is not suitable for this method")
        self.codelist.extend(templist)  ##finally updating our codelist with the corresponding instruction 
        
                    

    """
    Signature: self, code: Str
    Purpose:
        This method is supposed to work on a instruction of type "add/sub/eq..." and return the corresponding Hack assembly code as per the following pseudo specifications
            add: SP--; addr=*SP; D=*addr; SP--; addr=*SP; D=D + *addr; *addr=D; SP++                                                    //DONE
            sub: ---------------------------------------  D=D - *addr; *addr=D; SP++                                                    //DONE
            eq:  ---------------------------------------  D=D - *addr; addr=IFEQUAL; D;JEQ; *addr=0; SP++ (IFEQUAL); *addr=-1; SP++     //DONE
            gt:  ---------------------------------------  D=D - *addr; addr=IFGT; D;JGT; *addr=0; SP++; (IFGT); *addr=-1; SP++          //DONE
            lt:  ---------------------------------------  D=D - *addr; addr=IFLT; D;JLT; *addr=0; (IFLT); *addr=-1; SP++                //DONE
            and: ---------------------------------------  D=D & *addr; *addr=D; SP++                                                    //DONE
            or:  ---------------------------------------  D=D + *addr; *add=D; SP++                                                      //DONE
            not: SP--; addr=*SP; D=*addr; D= !D; *addr=D; SP++
            neg: ........................ D= -D; *addr=D; SP++
        We will also add a comment based code - for e.g. for push constant 100, 1st instruction will always be - "//push constant 100"
    """
    def writeArithemetic(self, code):
        templist = [] ##Templist in which we will store the relevant instructions
        templist.append("//"+" "+code) ##First instruction becomes comment 
        if code in ["add", "sub", "eq", "gt", "lt", "and", "or"]:
            templist.extend(self.decrementSP()) ##SP--
            templist.extend(self.setARegister("PointerSP", "0")) ##addr=*SP
            templist.extend(self.setDRegisterToComputation(None, None, "PointerAddr"))
            templist.extend(self.decrementSP()) ##SP--
            templist.extend(self.setARegister("PointerSP", "0")) ##addr=*SP
            if code == "add":
                templist.extend(self.setDRegisterToComputation("D","add", "PointerAddr")) ##D=D+*addr
                templist.append("M=D") #*addr=D
                templist.extend(self.incrementSP())
            elif code == "sub":
                templist.append("D=M-D") ## first - second
                templist.append("M=D")
                templist.extend(self.incrementSP())
            elif code == "and":
                templist.extend(self.setDRegisterToComputation("D","and", "PointerAddr")) ##D=D+*addr
                templist.append("M=D") #*addr=D
                templist.extend(self.incrementSP()) ##SP++
            elif code == "or":
                templist.extend(self.setDRegisterToComputation("D","or", "PointerAddr")) ##D=D+*addr
                templist.append("M=D") #*addr=D
                templist.extend(self.incrementSP()) #SP++
            elif code in ["eq", "gt", "lt"]:
                jump_map = {"eq": "JEQ", "gt": "JGT", "lt": "JLT"}
                label = code.upper() + "_" + str(self.label_counter)
                end_label = "END_" + code.upper() + "_" + str(self.label_counter)
                self.label_counter += 1
                templist.append("D=M-D")                                                    ## first - second  ## D = *addr - D
                templist.append("@" + label)                                                ## @IFEQ_0
                templist.append("D;" + jump_map[code])                                      ## D;JEQ
                ## False case
                templist.extend(["@SP", "A=M"])                                             ## reload target address
                templist.append("M=0")                                                      ## *SP = 0 (false)
                templist.extend(self.incrementSP())                                         ## SP++
                templist.append("@" + end_label)                                            ## @END_EQ_0
                templist.append("0;JMP")                                                    ## unconditional jump past true
                ## True case
                templist.append("(" + label + ")")                                          ## (EQ_0)
                templist.extend(["@SP", "A=M"])                                             ## reload target address
                templist.append("M=-1")                                                     ## *SP = -1 (true)
                templist.extend(self.incrementSP())                                         ## SP++
                ## End
                templist.append("(" + end_label + ")")  
        elif code in ["not", "neg"]:
            ##not: SP--; addr=*SP; D=*addr; D= !D; *addr=D; SP++
            ##neg: ........................ D= -D; *addr=D; SP++
            templist.extend(self.decrementSP()) ##SP--
            templist.extend(self.setARegister("PointerSP", "0")) ##addr=*SP
            templist.extend(self.setDRegisterToComputation(None, None, "PointerAddr")) ##D=*addr
            templist.extend(self.setDRegisterToComputation(None, code, "D")) ##D=!D or D=-D
            templist.append("M=D") ##*addr=D
            templist.extend(self.incrementSP())
        else:
            raise ValueError("The given command is not suitable for this method")
        self.codelist.extend(templist) ##finally updating our codelist with the corresponding instruction 
        
        
